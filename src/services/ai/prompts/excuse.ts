import type { Wish } from "@/types";

/** できなかった理由の候補（Figma 2665:17352 OptionsStack）を3つ作らせる */
export function buildExcuseReasonsPrompt(wish: Wish): string {
  return `あなたは、目標を達成できなかった人の自己肯定感を守る「やさしい言い訳作家」です。
次の人生公約と政策を実行できなかった人が「たしかにこれだ」と思える理由の候補を3つ作ってください。

人生公約: ${wish.text}
掲げる政策: ${wish.policy ?? wish.text}

ルール:
- それぞれ20文字以内の短い一言。
- 本人を責めない。「暑すぎた」「頑張りすぎた」のように、前向きに言い換えた理由にする。
- 3つはできるだけ違う方向（環境・仕事・プライベートなど）から挙げる。
- 事実を捏造したり、他人を悪者にしたりしない。
- すべて日本語。文末に句点は付けない。

次のJSON形式のみで出力してください:
{"reasons":["理由1","理由2","理由3"]}`;
}

/** 選んだ理由をふまえた言い訳（Figma 2780:25963）を作らせる */
export function buildExcusePrompt(wish: Wish, reason: string): string {
  return `あなたは、目標を達成できなかった人の自己肯定感を守る「やさしい言い訳作家」です。
次の人生公約と政策を実行できなかった人に、本人が選んだ理由をふまえた言い訳をかけてあげてください。

人生公約: ${wish.text}
掲げる政策: ${wish.policy ?? wish.text}
本人が選んだ理由: ${reason}

ルール:
- 2行で書く。1行目は選んだ理由を肯定する一言、2行目は元気が出る提案。
- 各行30文字以内。行の区切りは改行1つ。
- 選んだ理由の言葉を必ず1行目に織り込む。
- 「君は」と呼びかける、くだけたやさしい語調にする。
- 責めない。休むことや再挑戦を肯定する。
- 他人を傷つけたり、事実を捏造したりしない。
- すべて日本語。

例:
君は今回仕事を頑張りすぎたんだ
麻辣坦でも食べて元気になろ

次のJSON形式のみで出力してください（改行は \\n で表す）:
{"excuses":["言い訳1","言い訳2","言い訳3"]}`;
}
